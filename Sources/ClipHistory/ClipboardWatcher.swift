import AppKit

/// macOS has no "clipboard changed" notification, so we check the
/// pasteboard's change counter a few times a second.
@MainActor
final class ClipboardWatcher {
    private let store: HistoryStore
    private var timer: Timer?
    private var lastChange: Int
    var isPaused = false
    /// Called after something new is saved (drives the Dock animation).
    var onCapture: (() -> Void)?

    /// Types that password managers and other apps use to say "don't record this".
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(store: HistoryStore) {
        self.store = store
        lastChange = NSPasteboard.general.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !isPaused else { return }

        let types = pb.types ?? []
        if types.contains(where: { Self.skipTypes.contains($0.rawValue) }) { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        // 1. Files copied in Finder
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls, source: source)
            onCapture?()
            return
        }

        // 2. Images (screenshots, "Copy Image" in browsers, Preview, Photos…)
        let hasPlainText = types.contains(.string)
        if !hasPlainText, let img = Self.readImage(from: pb) {
            store.addImage(png: img.png, width: img.width, height: img.height, source: source)
            onCapture?()
            return
        }

        // 3. Text
        if let s = pb.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.addText(s, source: source)
            onCapture?()
            return
        }

        if let img = Self.readImage(from: pb) {
            store.addImage(png: img.png, width: img.width, height: img.height, source: source)
            onCapture?()
        }
    }

    static func readImage(from pb: NSPasteboard) -> (png: Data, width: Int, height: Int)? {
        if let d = pb.data(forType: .png), let rep = NSBitmapImageRep(data: d) {
            return (d, rep.pixelsWide, rep.pixelsHigh)
        }
        if let d = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: d),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        // JPEG, HEIC, PDF and other image types NSImage understands
        guard pb.canReadObject(forClasses: [NSImage.self], options: nil),
              let image = NSImage(pasteboard: pb),
              let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }
}
